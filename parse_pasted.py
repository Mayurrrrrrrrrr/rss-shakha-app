import re

lines = raw_text.split('\n')
parsed_data = []

# Regex for #1, #2 format
regex_hash = re.compile(r'^#\d+\s+(.+)$')
# Regex for 1., 2. format
regex_num = re.compile(r'^\d+\.\s+(.+)$')

current_author = None
current_content = []

def add_entry(content, author):
    if not content: return
    # remove leading quotes if any
    content = content.strip('“"” ')
    # if author is embedded like content — author
    if '—' in content:
        parts = content.split('—')
        author = parts[-1].strip()
        content = parts[0].strip()
    elif '-' in content and ' ' in content: # heuristic for author
        pass # too risky to split on hyphens generally
        
    # fix some obvious weird spacings
    content = content.replace(' ,', ',').replace(' ।', '।').replace(' !', '!')
    content = content.replace(' नहीं ,हीं ', ' नहीं, ')
    content = content.replace(' !च्चों ', '! ')
    content = content.replace(' उन्हों नेन्हों ने ', ' उन्होंने ')
    
    # deduplication
    content_normalized = content.replace(' ', '')
    if any(item['content'].replace(' ', '') == content_normalized for item in parsed_data):
        return
        
    parsed_data.append({
        'content': content,
        'author': author if author else ""
    })

# Process #1 format
